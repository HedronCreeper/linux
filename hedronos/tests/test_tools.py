"""The repo's own tools: generation must be reproducible and the gates must stay green.

SPDX-License-Identifier: MIT

These are subprocess tests on purpose. `hedronos-verify` runs the same tools, and the point of the
pair is that a contributor sees the identical failure from either direction — the slow parts (the
Kconfig scan over ~2000 files) are done once per class and reused.
"""
from __future__ import annotations

import json
import os
import subprocess
import unittest

from helpers import DATA_DIR, HEDRON_DIR, KERNEL_DIR, TempDirMixin, run_tool


class TestKernelConfig(unittest.TestCase):
    """The defconfig and the variant fragment: every symbol real, both files generated."""

    @classmethod
    def setUpClass(cls):
        if not os.path.isfile(os.path.join(KERNEL_DIR, "hedronos_defconfig")):
            raise unittest.SkipTest("no generated defconfig")
        cls.results = {}
        for name in ("hedronos_defconfig", "hedronos.fragment"):
            proc = run_tool("kconf-check.py", "--kernel", os.path.dirname(HEDRON_DIR),
                            "--config", os.path.join(KERNEL_DIR, name), "--json", timeout=900)
            cls.results[name] = (proc.returncode, proc.stdout, proc.stderr)

    def test_kconf_check_accepts_both_files(self):
        for name, (rc, out, err) in self.results.items():
            with self.subTest(file=name):
                try:
                    doc = json.loads(out)
                except json.JSONDecodeError:
                    self.fail("%s: kconf-check printed no JSON (rc=%d): %s" % (name, rc, err[-200:]))
                self.assertEqual(doc.get("unknown"), [], "%s names symbols this tree does not have" % name)
                self.assertEqual(doc.get("bad_lines"), [], "%s has lines kconfig cannot read" % name)
                self.assertTrue(doc.get("ok"), "%s: the gate said not ok" % name)

    def test_both_files_are_generated_and_large_enough(self):
        for name, min_symbols in (("hedronos_defconfig", 500), ("hedronos.fragment", 40)):
            path = os.path.join(KERNEL_DIR, name)
            text = open(path, encoding="utf-8").read()
            with self.subTest(file=name):
                self.assertIn("generated by hedronos/tools/gen-defconfig.py", text.splitlines()[0])
                self.assertGreaterEqual(sum(1 for l in text.splitlines() if l.startswith("CONFIG_")),
                                        min_symbols)
                self.assertTrue(os.path.isfile(path + ".sha256"), "no hash sidecar for %s" % name)
                recorded = open(path + ".sha256", encoding="utf-8").read().split()[0]
                import hashlib
                self.assertEqual(recorded, hashlib.sha256(text.encode()).hexdigest(),
                                 "%s does not match its sidecar: it was hand-edited" % name)

    def test_no_authoring_junk_survived_into_a_shipped_config(self):
        # Both failure modes happened once, by hand: a `? no:` note left in the middle of a line,
        # and `CONFIG_X=n`, which kconfig reads as a *value*, not as "off".
        for name in ("hedronos_defconfig", "hedronos.fragment"):
            text = open(os.path.join(KERNEL_DIR, name), encoding="utf-8").read()
            with self.subTest(file=name):
                self.assertNotIn("? no", text)
                self.assertNotIn("...", text)
                for line in text.splitlines():
                    self.assertFalse(line.startswith("CONFIG_") and line.endswith("=n"),
                                     "use '# CONFIG_X is not set' instead: %s" % line)
                    if line.startswith("# CONFIG_"):
                        self.assertTrue(line.endswith(" is not set"), "malformed: %s" % line)

    def test_the_spec_is_the_source_of_truth(self):
        # `--require` in the build is what stops a renamed symbol from silently disappearing; this
        # asserts the same thing from the report side, where the numbers are readable.
        proc = run_tool("gen-defconfig.py", "--kernel", os.path.dirname(HEDRON_DIR),
                        "--spec", os.path.join(KERNEL_DIR, "defconfig-spec.py"), "--report", timeout=900)
        self.assertEqual(proc.returncode, 0, proc.stderr[-300:])
        out = proc.stdout
        self.assertIn("MISSING (real)", out, "the generator did not report at all")
        self.assertIn("MISSING (real)      : 0", out,
                      "the spec names a symbol this kernel tree does not have")


class TestGeneration(TempDirMixin, unittest.TestCase):
    def test_gpu_db_regeneration_summary_is_the_shipped_shape(self):
        proc = run_tool("gen-gpu-db.py", "--kernel", os.path.dirname(HEDRON_DIR), "--summary", timeout=900)
        self.assertEqual(proc.returncode, 0, proc.stderr[-400:])
        nums = [int(x) for x in proc.stdout.replace("=", " ").split() if x.isdigit()]
        self.assertGreaterEqual(len(nums), 3, "expected vendor counts in --summary")
        db = json.load(open(os.path.join(DATA_DIR, "gpu-db", "gpu-db.json"), encoding="utf-8"))
        self.assertEqual(db.get("schema"), 3)
        self.assertGreater(len(db.get("vendors", {})), 1)

    def test_gpu_plans_are_generated_and_complete(self):
        tmp = self.mktemp()
        out = os.path.join(tmp, "plans.json")
        summary = os.path.join(tmp, "summary.txt")
        proc = run_tool("hedron-gpu-plans.py", "--db", os.path.join(DATA_DIR, "gpu-db", "gpu-db.json"),
                        "--rules", os.path.join(DATA_DIR, "driver-rules.toml"), "--out", out,
                        "--summary", summary, "--version", "0-test", timeout=600)
        self.assertEqual(proc.returncode, 0, proc.stderr[-400:])
        doc = json.load(open(out, encoding="utf-8"))
        self.assertTrue(str(doc["format"]).startswith("hedron"), "unexpected format %r" % doc["format"])
        self.assertEqual(doc["plan_count"], len(doc["plans"]), "the header count and the list disagree")
        self.assertGreaterEqual(len(doc["plans"]), 50)
        for plan in doc["plans"][:20]:
            self.assertTrue(plan.get("packages") or plan.get("actions"),
                            "plan %s does nothing" % plan.get("id"))
        self.assertTrue(os.path.getsize(summary) > 0, "no summary written")

    def test_boot_entries_render_for_the_shipped_spec(self):
        tmp = self.mktemp()
        proc = run_tool("hedron-boot-entries.py", "--spec", os.path.join(DATA_DIR, "boot-entries.toml"),
                        "--outdir", os.path.join(tmp, "entries"), "--loader-conf", os.path.join(tmp, "loader.conf"),
                        "--grub-out", os.path.join(tmp, "grub.cfg"), "--profile", "gamerte", timeout=300)
        self.assertEqual(proc.returncode, 0, proc.stderr[-400:])
        entries = os.listdir(os.path.join(tmp, "entries"))
        self.assertGreaterEqual(len(entries), 3)
        for name in entries:
            text = open(os.path.join(tmp, "entries", name), encoding="utf-8").read()
            self.assertIn("linux", text.lower(), "%s has no kernel line" % name)
        self.assertTrue(os.path.getsize(os.path.join(tmp, "grub.cfg")) > 100)


class TestPkgset(unittest.TestCase):
    """Every profile must resolve, and must resolve to something installable."""

    @classmethod
    def setUpClass(cls):
        import tempfile
        cls.tmp = tempfile.mkdtemp(prefix="hedron-pkgset-")
        cls.docs = {}
        for profile in ("gamerte", "desktop", "handheld", "studio", "core"):
            path = os.path.join(cls.tmp, "%s.json" % profile)
            proc = run_tool("pkgset.py", "resolve", "--profile", profile, "--variant", "dvd",
                            "--arch", "x86_64", "--json", path, "--fail-on-error", timeout=300)
            if proc.returncode != 0:
                raise AssertionError("%s failed to resolve: %s" % (profile, proc.stderr[-300:]))
            cls.docs[profile] = json.load(open(path, encoding="utf-8"))

    @classmethod
    def tearDownClass(cls):
        import shutil
        shutil.rmtree(cls.tmp, ignore_errors=True)

    @staticmethod
    def _names(doc):
        # resolve --json stores a package as an object (name, source, group, reason, tier, size);
        # a test that assumed bare strings would pass the day it was written and fail the day the
        # report got richer, which is the wrong way round for both files.
        return {p["name"] if isinstance(p, dict) else p for p in doc.get("packages", [])}

    def test_the_floor_set_is_in_every_profile_and_nothing_is_orphaned(self):
        # Two separate promises, and the distinction matters: `core` means "fewer things", not
        # "broken things" — so what every profile must carry is the declared floor, while the
        # stronger "the whole layer" rule applies to the flagship. What must never happen is a
        # package in packages/ that no profile installs: that is a package nobody tests.
        from hedronlib.util import load_toml
        sets = load_toml(os.path.join(DATA_DIR, "package-sets.toml"))
        floor = list(sets.get("hedron", {}).get("core", []))
        self.assertGreaterEqual(len(floor), 5, "no floor declared in package-sets.toml")
        everything = {d for d in os.listdir(os.path.join(HEDRON_DIR, "packages")) if d.startswith("hedronos-")}
        covered = set()
        for profile, doc in self.docs.items():
            names = self._names(doc)
            covered |= names & everything
            with self.subTest(profile=profile):
                missing = [q for q in floor if q not in names]
                self.assertEqual(missing, [], "%s does not install %s" % (profile, ", ".join(missing)))
        self.assertEqual(covered, everything, "orphaned package(s): %s" % ", ".join(sorted(everything - covered)))
        gaming = self._names(self.docs["gamerte"])
        for extra in ("hedronos-gamemode", "hedronos-capture", "hedronos-overlay", "hedronos-vitals",
                      "hedronos-session", "hedronos-handheld", "hedronos-kde"):
            self.assertIn(extra, gaming, "the gaming profile is missing %s" % extra)

    def test_resolution_records_where_packages_came_from(self):
        # Every entry says which group pulled it in and which back end provides it, because
        # "why is this package here" is the first question a mirror operator asks.
        for profile, doc in self.docs.items():
            with self.subTest(profile=profile):
                self.assertGreater(len(doc.get("packages", [])), 20)
                self.assertEqual(doc.get("errors", []), [], "resolver reported errors")
                self.assertEqual(doc.get("count"), len(doc.get("packages", [])))
                self.assertTrue(doc.get("size_mib", 0) > 0, "no size report")
                for pkg in doc["packages"]:
                    if not isinstance(pkg, dict):
                        continue
                    self.assertIn("source", pkg, "%s has no back end" % pkg.get("name"))
                    self.assertTrue(pkg.get("group") or pkg.get("reason"),
                                    "%s arrived for no stated reason" % pkg.get("name"))

    def test_core_profile_has_no_desktop_apps(self):
        doc = self.docs["core"]
        names = self._names(doc)
        self.assertNotIn("plasma-meta", names)
        self.assertNotIn("sddm", names)

    def test_digest_is_stable(self):
        import subprocess, sys
        one = subprocess.run([sys.executable, os.path.join(HEDRON_DIR, "tools", "pkgset.py"), "digest",
                              "--json", os.path.join(self.tmp, "gamerte.json")],
                             capture_output=True, text=True, cwd=HEDRON_DIR)
        two = subprocess.run([sys.executable, os.path.join(HEDRON_DIR, "tools", "pkgset.py"), "digest",
                              "--json", os.path.join(self.tmp, "gamerte.json")],
                             capture_output=True, text=True, cwd=HEDRON_DIR)
        self.assertEqual(one.returncode, 0, one.stderr[-200:])
        self.assertEqual(one.stdout.strip(), two.stdout.strip(), "the digest moved between runs")

    def test_select_filters_by_source(self):
        import subprocess, sys
        proc = subprocess.run([sys.executable, os.path.join(HEDRON_DIR, "tools", "pkgset.py"), "select",
                              "--json", os.path.join(self.tmp, "gamerte.json"), "--source", "flatpak"],
                              capture_output=True, text=True, cwd=HEDRON_DIR)
        self.assertEqual(proc.returncode, 0, proc.stderr[-300:])
        lines = [l for l in proc.stdout.splitlines() if l.strip()]
        self.assertTrue(all("@" not in l for l in lines), "a non-flatpak entry slipped through")


class TestVerifierAndPackaging(unittest.TestCase):
    def test_verify_lists_every_group_with_an_explanation(self):
        # A `--only`/`--skip` list is how anyone narrows a 22-check gate, so the group names and
        # their one-line descriptions are the interface. An empty description means the docstring
        # was never written.
        proc = run_tool("hedronos-verify", "--list", timeout=120)
        self.assertEqual(proc.returncode, 0, proc.stderr[-200:])
        rows = [l for l in proc.stdout.splitlines() if l.strip()]
        self.assertGreaterEqual(len(rows), 15)
        for line in rows:
            name, _, rest = line.partition(" ")
            self.assertTrue(name and not name.startswith("-"), "unexpected row %r" % line)
            self.assertTrue(rest.strip(), "check group %r has no description" % name)

    def test_mkhedronpkg_dry_run_counts_the_trees(self):
        for pkg in ("hedronos-release", "hedronos-gamemode", "linux-hedron"):
            proc = run_tool("mkhedronpkg", "--src", os.path.join(HEDRON_DIR, "packages", pkg),
                            "--dry-run", timeout=300)
            with self.subTest(package=pkg):
                self.assertEqual(proc.returncode, 0, (proc.stdout + proc.stderr)[-400:])
                digits = [w for w in proc.stdout.replace(",", " ").split() if w.isdigit()]
                self.assertTrue(digits, "no file count reported for %s" % pkg)

    def test_lint_shell_passes_on_the_tree(self):
        proc = subprocess.run(["bash", os.path.join(HEDRON_DIR, "tools", "lint-shell.sh"), "--root", HEDRON_DIR],
                              capture_output=True, text=True, cwd=HEDRON_DIR, timeout=300)
        self.assertEqual(proc.returncode, 0, proc.stdout[-300:] + proc.stderr[-300:])

    def test_iso_manifest_lint_reports_and_exits_cleanly(self):
        # Either there is a rehearsal to lint (then it must be consistent) or there is not (then the
        # tool must say so and exit 1 — not crash).
        proc = run_tool("iso-manifest.py", "lint", "--root", HEDRON_DIR, timeout=120)
        self.assertIn(proc.returncode, (0, 1))
        self.assertTrue(proc.stdout.strip() or proc.stderr.strip())
        self.assertNotIn("Traceback", proc.stderr)

