#!/usr/bin/env python3
# SPDX-License-Identifier: MIT
"""gen-defconfig.py — turn the intent list into a defconfig whose every line exists.

Same idea as the GPU database generator: the *generator* is the source of truth, the checked-in
file is a build product with a hash next to it. A hand-edited defconfig picks up a typo'd or
renamed symbol and nobody notices for a year, because kconfig just drops it. Here every symbol is
looked up in the kernel tree's own Kconfig files; unknown names are either dropped with a report
(default, so `make defconfig` still works) or a hard error (--require), which is what the CI gate
and `hedronos-verify` use.

    tools/gen-defconfig.py --kernel . --out hedronos/kernel/hedronos_defconfig
    tools/gen-defconfig.py --kernel . --report            # what got dropped and why

The `?` suffix on a symbol name is the escape hatch: `CONFIG_FOO?` means "we would like this; drop
it quietly if the tree does not have it". It is a *marked* guess, so the report shows exactly how
many of our wishes the kernel declined.
"""

from __future__ import annotations

import argparse
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from kconf_check_lib import collect_symbols  # noqa: E402


def load_spec(path: str) -> list[tuple[str, str, str, str]]:
    ns: dict = {}
    with open(path, encoding="utf-8") as fh:
        code = compile(fh.read(), path, "exec")
    exec(code, ns)
    return list(ns["SPEC"])


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(prog="gen-defconfig", description=__doc__.splitlines()[0],
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--kernel", default="..", help="kernel source tree (the repo root)")
    ap.add_argument("--spec", default=None, help="SPEC python file (default: hedronos/kernel/defconfig-spec.py)")
    ap.add_argument("--out", default=None, help="write here")
    ap.add_argument("--report", action="store_true", help="print what was dropped, then exit")
    ap.add_argument("--require", action="store_true", help="unknown non-guess symbols are an error")
    args = ap.parse_args(argv)

    kernel = os.path.abspath(args.kernel)
    spec = args.spec or os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))),
                                     "kernel", "defconfig-spec.py")
    if not os.path.isfile(spec):
        print("gen-defconfig: no spec at %s" % spec, file=sys.stderr)
        return 2
    entries = load_spec(spec)
    symbols, where = collect_symbols(kernel)
    hedron_root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

    lines = ["# HedronOS kernel configuration — generated by hedronos/tools/gen-defconfig.py.",
             "#",
             "# SPDX-License-Identifier: MIT",
             "#",
             "# Do not hand-edit: change the spec (hedronos/kernel/defconfig-spec.py) and regenerate.",
             "# Every symbol here was found in this tree's Kconfig files; the generator drops names",
             "# it cannot find, and --require turns those drops into a build error.",
             ""]
    seen: set[str] = set()
    deduped: list[str] = []
    real_dropped: list[str] = []
    guesses: list[str] = []
    groups: dict[str, list[str]] = {}
    for group, sym, value, note in entries:
        bare = sym.replace("CONFIG_", "", 1)
        guess = bare.endswith("?")
        if guess:
            bare = bare[:-1]
        key = "CONFIG_" + bare
        if bare in seen:
            deduped.append(key)      # same symbol twice is a tidiness bug, not a wrong one
            continue
        if bare not in symbols:
            (guesses if guess else real_dropped).append(key)
            continue
        seen.add(bare)
        # Never a trailing comment on a CONFIG_ line. kconfig's own parser (conf --defconfig,
        # scripts/kconfig/merge_config.sh) reads the line whole, and tools/kconf-check.py is strict
        # for exactly that reason: `CONFIG_X=y # why` is a *bad line*, not a documented one. The
        # note therefore goes on its own comment line above the setting, where it is free to be a
        # sentence and where a reader still sees why the symbol is there.
        if note and not guess:
            groups.setdefault(group, []).append("# %s: %s" % (bare, note))
        if value == "n":
            groups.setdefault(group, []).append("# CONFIG_%s is not set" % bare)
        else:
            val = value if value.startswith("=") else "=" + value
            groups.setdefault(group, []).append("%s%s" % (key, val))

    titles = {"build": "build, IPC and the syscall surface we depend on",
              "latency": "latency: tickless, 300 Hz, no RCU callbacks on the game CPUs",
              "sched": "scheduler: sched_ext, core scheduling, group identity",
              "cgroup": "cgroups: the container of a game is a cgroup, so tune them",
              "bpf": "BPF: the plumbing half of HedronOS (sched_ext, FlowState, gamemode)",
              "tracing": "tracing: how hedron-latency and hedron-doctor see the kernel",
              "power": "power: governors, RAPL, thermal, suspend and hibernation",
              "memory": "memory: zswap, LRU gen, huge pages, zero-on-alloc",
              "security": "security: lockdown, module signing, verity, TPM, keyring",
              "gpu": "graphics: amdgpu, i915, xe, nova, nouveau, radeon, kms",
              "sound": "audio: HDA (including the codec list), SOF, USB audio, OSS compat",
              "input": "input and HID: controllers, wheels, pads, touch, the handheld keys",
              "iio": "IIO: accelerometers for tablet/Handheld auto-rotate",
              "usb": "USB and Thunderbolt/USB4",
              "net": "networking: BBR, wireguard, nftables, wifi, bluetooth",
              "fs": "filesystems: btrfs (the install default), ext4, xfs, f2fs, NTFS3, network",
              "block": "block: NVMe, AHCI, RAID, dm, DAX",
              "crypto": "crypto: hardware-accelerated, plus the compression libs",
              "platform": "platform drivers: vendor laptops, handhelds, tablets",
              "sensors": "sensors and watchdogs: what hedron-vitals reads",
              "virt": "virtualisation: KVM/SEV/TDX, so a HedronOS box can host a Windows VM",
              "multimedia": "media/I2C/GPIO: capture cards, webcams, boards",
              "fw": "firmware, EFI, printk and the /proc+/sys surface"}
    for group in sorted(groups, key=lambda g: list(titles).index(g) if g in titles else 99):
        lines.append("")
        lines.append("# " + "-" * 74)
        lines.append("# %s" % titles.get(group, group))
        lines.append("# " + "-" * 74)
        lines.extend(groups[group])
    text = "\n".join(lines) + "\n"

    if args.report:
        print("spec entries        : %d" % len(entries))
        print("written             : %d" % len(seen))
        print("unfulfilled guesses : %d (marked with '?', dropped silently)" % len(guesses))
        for name in guesses:
            print("    guess  %s" % name)
        if deduped:
            print("deduplicated        : %d (%s)" % (len(deduped), ", ".join(sorted(set(deduped)))))
        print("MISSING (real)      : %d" % len(real_dropped))
        for name in real_dropped:
            print("    miss   %s" % name)
        return 0
    if real_dropped and args.require:
        print("gen-defconfig: %d symbol(s) in the spec do not exist in %s: %s"
              % (len(real_dropped), kernel, ", ".join(real_dropped)), file=sys.stderr)
        return 1
    if args.out:
        os.makedirs(os.path.dirname(args.out) or ".", exist_ok=True)
        with open(args.out, "w", encoding="utf-8") as fh:
            fh.write(text)
        sha = None
        try:
            sys.path.insert(0, os.path.join(hedron_root, "tools"))
            from hedronlib.util import sha256_text
            sha = sha256_text(text)
        except Exception:  # noqa: BLE001
            pass
        if sha:
            with open(args.out + ".sha256", "w", encoding="utf-8") as fh:
                fh.write(sha + "\n")
        print("wrote %s (%d symbols, %d unfulfilled guesses, %d missing)"
              % (args.out, len(seen), len(guesses), len(real_dropped)))
        if real_dropped and args.require:
            print("gen-defconfig: %d missing symbol(s) despite --require" % len(real_dropped), file=sys.stderr)
    else:
        sys.stdout.write(text)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
