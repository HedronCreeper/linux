"""Generate systemd-boot loader entries (and a GRUB menu) from data/boot-entries.toml.

Shipped as /usr/lib/hedron/boot-entries.py by hedronos-release, because the installed
system needs to regenerate entries too — after a kernel package update, after
`hedron-tune profile set studio` changes the default, and after a rollback.

    hedron-boot-entries --spec data/boot-entries.toml --outdir /boot/loader/entries \
        --version 1.0.0 --codename Halcyon --profile gamerte [--print]
"""

from __future__ import annotations

import argparse
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

from hedronlib.util import load_toml  # noqa: E402

HEADER = "## generated by hedron-boot-entries — edit the spec, not this file"


def should_include(entry: dict, profile: str, variant: str) -> bool:
    if not entry.get("enabled", True):
        return False
    when = entry.get("when", {}) or {}
    if "profiles" in when and profile not in when["profiles"]:
        return False
    if "not_profiles" in when and profile in when["not_profiles"]:
        return False
    if "variants" in when and variant not in when["variants"]:
        return False
    return True


def render_entries(spec: dict, profile: str, version: str, codename: str,
                   variant: str = "dvd") -> tuple[dict[str, str], list[str]]:
    """Return ({filename: content}, [default_ids])."""
    out: dict[str, str] = {}
    defaults: list[str] = []
    common = list(spec.get("common_options", []))
    for entry in spec.get("entries", []):
        if not should_include(entry, profile, variant):
            continue
        fmt = {"version": version, "codename": codename, "profile": profile, "variant": variant}
        ident = entry["id"].format(**fmt)
        lines = [HEADER,
                 "title      " + entry["title"].format(**fmt)]
        if entry.get("efi"):
            lines.append("efi        %s" % entry["efi"].format(**fmt))
        else:
            lines.append("linux      %s" % entry["linux"].format(**fmt))
        initrds = entry.get("initrd") or []
        if isinstance(initrds, str):
            initrds = [initrds]
        for img in initrds:
            lines.append("initrd     %s" % img.format(**fmt))
        if entry.get("devicetree"):
            lines.append("devicetree %s" % entry["devicetree"].format(**fmt))
        options = [o.format(**fmt) for o in entry.get("options", [])] + common
        if options:
            lines.append("options    " + " ".join(options))
        if entry.get("grab"):
            lines.append("grab       %s" % entry["grab"])
        if entry.get("grub_users"):
            lines.append("grub_users %s" % entry["grub_users"])
        out[ident + ".conf"] = "\n".join(lines) + "\n"
        if entry.get("default"):
            defaults.append(ident)
    return out, defaults


def render_loader_conf(spec: dict, defaults: list[str], version: str) -> str:
    timeout = spec.get("timeout", 4)
    lines = ["# HedronOS %s — systemd-boot configuration (generated)" % version,
             "timeout %s" % timeout,
             "default  %s" % (defaults[0] + ".conf" if defaults else "linux"),
             "console-mode keep",
             "beep no",
             "# Shows a 'Firmware Setup' entry on UEFI systems that advertise it.",
             "auto-firmware-settings yes",
             ""]
    return "\n".join(lines)


def render_grub_menu(spec: dict, profile: str, version: str, codename: str,
                     variant: str = "dvd") -> str:
    """A GRUB menu that mirrors the loader entries, for BIOS firmware and fallback."""
    entries, _ = render_entries(spec, profile, version, codename, variant)
    blocks = [
        "# HedronOS %s — GRUB menu (generated by hedron-boot-entries)" % version,
        "set timeout=%s" % spec.get("timeout", 4),
        "set default=0",
        "insmod part_gpt", "insmod fat", "insmod ext2", "insmod iso9660",
        "insmod all_video", "insmod gfxterm",
        "set gfxmode=auto", "terminal_output gfxterm", "",
    ]
    for name, body in entries.items():
        title = ""
        linux = ""
        initrds: list[str] = []
        options = ""
        for line in body.splitlines():
            key, _, value = line.partition(" ")
            if key == "title":
                title = value.strip()
            elif key == "linux":
                linux = value.strip()
            elif key == "initrd":
                initrds.append(value.strip())
            elif key == "options":
                options = value.strip()
            elif key == "efi":
                linux = ""
                title = title or "EFI boot"
                blocks.append("menuentry '%s' {" % title)
                blocks.append("  chainloader %s" % value.strip())
                blocks.append("}")
                blocks.append("")
                break
        if not linux:
            continue
        blocks.append("menuentry '%s' {" % title)
        blocks.append("  linux %s %s" % (linux, options))
        if initrds:
            blocks.append("  initrd %s" % " ".join(initrds))
        blocks.append("}")
        blocks.append("")
    return "\n".join(blocks) + "\n"


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--spec", required=True)
    ap.add_argument("--outdir", default=None, help="where to write loader entries")
    ap.add_argument("--grub-out", default=None, help="also write a grub.cfg here")
    ap.add_argument("--loader-conf", default=None, help="also write loader.conf here")
    ap.add_argument("--version", default="0.0.0")
    ap.add_argument("--codename", default="Halcyon")
    ap.add_argument("--profile", default="gamerte")
    ap.add_argument("--variant", default="dvd")
    ap.add_argument("--print", action="store_true", dest="do_print")
    args = ap.parse_args(argv)

    spec = load_toml(args.spec)
    entries, defaults = render_entries(spec, args.profile, args.version, args.codename, args.variant)
    if not entries:
        print("no boot entries matched profile=%s" % args.profile, file=sys.stderr)
        return 1
    if args.do_print:
        for name in sorted(entries):
            print("### %s" % name)
            print(entries[name])
    if args.outdir:
        os.makedirs(args.outdir, exist_ok=True)
        for existing in os.listdir(args.outdir):
            if existing.startswith("hedronos") and existing.endswith(".conf"):
                os.unlink(os.path.join(args.outdir, existing))
        for name, body in entries.items():
            with open(os.path.join(args.outdir, name), "w", encoding="utf-8") as fh:
                fh.write(body)
        print("wrote %d loader entries to %s (default=%s)"
              % (len(entries), args.outdir, defaults[0] + ".conf" if defaults else "-"))
    if args.loader_conf:
        os.makedirs(os.path.dirname(args.loader_conf) or ".", exist_ok=True)
        with open(args.loader_conf, "w", encoding="utf-8") as fh:
            fh.write(render_loader_conf(spec, defaults, args.version))
    if args.grub_out:
        os.makedirs(os.path.dirname(args.grub_out) or ".", exist_ok=True)
        with open(args.grub_out, "w", encoding="utf-8") as fh:
            fh.write(render_grub_menu(spec, args.profile, args.version, args.codename, args.variant))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
